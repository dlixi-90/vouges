import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// Public Google Fonts assets only. Font binaries are checked into public/fonts;
// normal builds and page views do not contact a third-party font service.
const directory = new URL("../public/fonts/", import.meta.url);
await mkdir(directory, { recursive: true });
const response = await fetch("https://fonts.googleapis.com/css2?family=Inter:ital,opsz,wght@0,14..32,100..900;1,14..32,100..900&family=Lora:ital,wght@0,400..700;1,400..700&display=swap", {
  headers: { "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36" },
});
if (!response.ok) throw new Error(`Font stylesheet: ${response.status}`);
const source = await response.text();
const blocks = [...source.matchAll(/\/\* (vietnamese|latin) \*\/\s*(@font-face\s*\{[^}]+\})/g)];
if (blocks.length !== 8) throw new Error(`Expected eight Latin/Vietnamese font faces, got ${blocks.length}`);
const styles = await Promise.all(blocks.map(async ([, subset, block]) => {
  const family = block.match(/font-family:\s*'([^']+)'/)[1].toLowerCase();
  const style = block.match(/font-style:\s*([^;]+);/)[1];
  const url = block.match(/url\((https:[^)]+)\)/)[1];
  if (new URL(url).hostname !== "fonts.gstatic.com") throw new Error("Unexpected font origin");
  const font = await fetch(url);
  if (!font.ok) throw new Error(`Font binary: ${font.status}`);
  const binary = Buffer.from(await font.arrayBuffer());
  const hash = createHash("sha256").update(binary).digest("hex").slice(0, 10);
  const filename = `${family}-${style}-${subset}-${hash}.woff2`;
  await writeFile(new URL(filename, directory), binary);
  console.log(`${filename}: ${binary.length} bytes`);
  return `/* ${family}: ${style}, ${subset} */\n${block.replace(url, `/fonts/${filename}`)}`;
}));
for (const family of ["lora", "inter"]) {
  const license = await fetch(`https://raw.githubusercontent.com/google/fonts/main/ofl/${family}/OFL.txt`);
  if (!license.ok) throw new Error(`Font license: ${license.status}`);
  await writeFile(new URL(`${family}-OFL.txt`, directory), await license.text());
}
await writeFile(new URL("../src/fonts.css", import.meta.url), `/* Self-hosted Lora/Inter; licenses in public/fonts. Generated by scripts/vendor-fonts.mjs. */\n${styles.join("\n")}\n`);
