import express from "express";
import authUser,{requireOwner} from "../middleware/authMiddleware.js";
import * as controller from "../controllers/loyaltyController.js";
const router=express.Router();
router.use(authUser);
router.get("/me",controller.myLoyalty);
router.get("/ledger",controller.myLedger);
router.post("/redeem",controller.redeemReward);
router.post("/claim",controller.claimPrivilege);
router.patch("/notifications/:id",controller.readNotification);
router.use("/admin",requireOwner);
router.get("/admin",controller.adminOverview);
router.put("/admin/policy",controller.adminPolicy);
router.post("/admin/rewards",controller.adminReward);
router.put("/admin/rewards/:id",controller.adminReward);
router.post("/admin/campaigns",controller.adminCampaign);
router.put("/admin/campaigns/:id",controller.adminCampaign);
router.get("/admin/members",controller.adminMembers);
router.get("/admin/members/:id",controller.adminMember);
router.post("/admin/members/:id/points",controller.adminPoints);
router.post("/admin/members/:id/tier",controller.adminTier);
router.post("/admin/orders/:id/refund",controller.adminRefund);
router.get("/admin/orders/:id",controller.adminOrder);
router.post("/admin/claims/:id/review",controller.adminResolveClaim);
router.get("/admin/redemptions",controller.adminRequests);
router.patch("/admin/redemptions/:id",controller.adminRequestStatus);
router.get("/admin/audit",controller.adminAudit);
router.post("/admin/maintain",controller.adminMaintain);
export default router;
